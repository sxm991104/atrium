def get_prompt() -> str:
    """给模型的完整手册。

    ⚠️ 顺序：先说"你是谁、能干什么"，再说"派活怎么派"。

        反过来（先讲派活细节）的话，模型会以为自己只会派活 ——
        这是原来那版的问题：2822 字全在讲怎么派活，
        工具表里另外十几个工具，一句都没提。
    """
    return FRONT_DESK_HEAD + _SEP + FRONT_DESK_DOC
